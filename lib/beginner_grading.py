"""A witnessed <=3 Double boundary, not a forced numeric label.

The old fixed21-neighbor corpus has only two official D3 examples and no D1/D2.
We may certify D3 only when an output is temporally no more complex than an
actually authored D3 AND its independently replayed beginner movement caps pass.
All other outputs retain the general corpus estimate.
"""
from pathlib import Path
import json,math
R=Path(__file__).resolve().parent
FEATURES=('row_nps','note_nps','peak_row_1s','peak_row_4s','peak_row_8s','jump_rows','hold_heads','offbeat_rows','sixteenth_rows')

def references():
    path=R/'BEGINNER_DOUBLE_REFERENCES.json'
    if not path.exists():path=R/'low_double_calibration/references.json'
    if not path.exists():return []
    return [r for r in json.loads(path.read_text(encoding='utf8'))['references'] if r['level']==3 and r['authored_native'] and not r['autogenerated']]

def certify(metrics,footmetrics,refs=None):
    if footmetrics.get('max_distance',math.inf)>math.sqrt(2)+1e-6:return None
    if footmetrics.get('max_speed',math.inf)>3.5+1e-6:return None
    if footmetrics.get('max_facing_delta',math.inf)>60+1e-6:return None
    witnesses=[]
    for row in references() if refs is None else refs:
        if all(float(metrics[k])<=float(row[k])+1e-5 for k in FEATURES):witnesses.append(row)
    if not witnesses:return None
    witness=min(witnesses,key=lambda r:sum((float(r[k])-float(metrics[k]))/(1+float(r[k])) for k in FEATURES))
    return dict(level=3,provisional=True,method='Componentwise native authored D3 witness plus stricter independently replayed beginner spatial caps',witness_title=witness.get('title'),witness_game_song_id=witness.get('game_song_id'),witness_sha256=witness.get('sha256'),witness_metrics={k:witness[k] for k in FEATURES},candidate_metrics=metrics,max_distance_cap=math.sqrt(2),max_speed_cap=3.5,max_facing_delta_cap=60,human_playtest_pending=True)

def certify_single(metrics,footmetrics,refs=None):
    if refs is None:
        path=R/'BEGINNER_SINGLE_REFERENCES.json'
        refs=json.loads(path.read_text(encoding='utf8'))['references'] if path.exists() else []
    refs=[r for r in refs if r.get('mode')==0 and r['level']==3 and r['authored_native'] and not r['autogenerated']]
    result=certify(metrics,footmetrics,refs)
    if result:
        witness=next(r for r in refs if r.get('sha256')==result['witness_sha256'])
        result.update(method='Componentwise official S3 metric witness plus stricter independently replayed beginner spatial caps',witness_hash_kind=witness.get('witness_hash_kind'),official_metrics_sha256=witness.get('official_metrics_sha256'),mode='Single')
    return result
